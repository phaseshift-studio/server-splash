#!/bin/bash
# Install the built splash binary on a remote host and verify it runs.
#
# A non-interactive `ssh host 'splash ...'` does not source your shell profile, so
# anything in ~/.cargo/bin or ~/.local/bin is invisible to it. Installing into
# /usr/local/bin (which is on the default PATH) makes the plain `ssh host 'splash ...'`
# form work.
#
# Usage:
#   scripts/install-remote.sh [HOST] [--dest PATH]
#
# Defaults: HOST=ginger, dest=/usr/local/bin/splash
set -euo pipefail

HOST="ginger"
DEST="/usr/local/bin/splash"

while [ $# -gt 0 ]; do
    case "$1" in
        --dest) DEST="$2"; shift 2 ;;
        -h|--help) sed -n '2,12p' "$0"; exit 0 ;;
        *) HOST="$1"; shift ;;
    esac
done

BIN="${SPLASH_BIN:-./target/release/splash}"
if [ ! -x "$BIN" ]; then
    echo "error: '$BIN' not found. Build it with: cargo build --release" >&2
    exit 1
fi

# Refuse to ship a binary older than the sources it was built from. Without this the
# install succeeds, the deploy succeeds, and the page is regenerated by the *previous*
# build — which looks exactly like "my changes did nothing".
newer_source="$(find src Cargo.toml build.rs -type f -newer "$BIN" -print -quit 2>/dev/null || true)"
if [ -n "$newer_source" ]; then
    echo "error: $BIN is older than $newer_source" >&2
    echo "       rebuild first:  cargo build --release" >&2
    echo "       (override with SPLASH_BIN=/path/to/other/binary if that is deliberate)" >&2
    exit 1
fi

echo "Binary: $BIN ($(du -h "$BIN" | cut -f1))"
echo "Target: $HOST:$DEST"
echo

echo "==> Checking the remote host"
ssh "$HOST" 'uname -m; (ldd --version 2>/dev/null || echo "no ldd") | head -1'

echo
echo "==> Copying to $HOST:/tmp/splash.new"
scp -q "$BIN" "$HOST:/tmp/splash.new"

echo "==> Installing to $DEST (needs sudo)"
# -t so sudo can prompt for a password; without a TTY a passwordless sudo still works.
ssh -t "$HOST" "sudo install -m 0755 /tmp/splash.new '$DEST' && rm -f /tmp/splash.new"

echo
echo "==> Verifying"
# No profile is sourced here on purpose: this is exactly how the deploy command runs.
ssh "$HOST" "'$DEST' --version"

cat <<EOF

Installed on $HOST as $DEST.

Next, in order:

  1. Preview it at http://$HOST.local/preview/ — the live page is untouched.
     (A subdirectory is used rather than /tmp precisely so you can look at it in a
     browser; the page is self-contained, so it works from any path.)

     ssh -t $HOST 'sudo splash --auto --hostname $HOST.local \
         --glances http://$HOST.local:61208 --deploy /var/www/html/preview'

  2. Happy? Go live. The page being replaced is backed up first and the restore
     command is printed.

     ssh -t $HOST 'sudo splash --auto --hostname $HOST.local \
         --deploy /var/www/html --glances http://$HOST.local:61208'

  3. Tidy up.

     ssh -t $HOST 'sudo rm -rf /var/www/html/preview'

Two things worth knowing:

  * --hostname is set explicitly. Left to itself the tool uses the machine's hostname
    and appends .local, but on a machine whose hostname or resolver differs that is a
    guess, and every link on the page depends on it.

  * --glances must name the host the way your *browser* reaches it. "localhost" there
    means the computer displaying the page, not $HOST, so the GPU panel silently stays
    empty. The tool warns when it sees a loopback URL.

  sudo is worth it: it lets 'ss -p' report process names and lets docker be read, which
  materially improves the names and descriptions on the page.

To keep it fresh automatically, deploy/splash.service and deploy/splash.timer rebuild
the page every 15 minutes:

  scp deploy/splash.{service,timer} $HOST:/tmp/
  ssh -t $HOST 'sudo mv /tmp/splash.{service,timer} /etc/systemd/system/ && \
      sudo systemctl daemon-reload && sudo systemctl enable --now splash.timer'
EOF
